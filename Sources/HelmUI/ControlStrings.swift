import Foundation

/// Control labels more than one module draws.
///
/// The same argument as `HelmSectionName`, one class of string over: two pages
/// send a person to the same pane of System Settings, and each had written its
/// own label for it. Leftovers said «Manage…» and the Uninstaller «Open
/// Extensions…», both over `PermissionCheck.openExtensionSettings()` — one act
/// with two names, and the vaguer of the two described nothing the app does.
///
/// One declaration rather than two agreeing ones, for the reason
/// `VPNStr.secretNeedsAPress` is built the way it is: a pair kept in step by
/// review drifts the first time one side is edited, and a pair that cannot
/// differ needs no review at all.
public enum HelmControlName {
    /// Opens System Settings → General → Login Items & Extensions. Named for the
    /// act, and perfective in the languages that mark it — a button that does one
    /// thing when pressed.
    public static var openExtensions: String { L("Open Extensions…") }
}
